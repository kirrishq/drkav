const text = (value) => ({ type: "text", text: value });
const paragraph = (value) => ({ type: "paragraph", children: [text(value)] });

const richText = (sectionKey, heading, body, showInPageNavigation = true) => ({
  __component: "operation.rich-text-section",
  sectionKey,
  heading,
  body: body.map(paragraph),
  showInPageNavigation,
});

const listSection = (sectionKey, heading, items, options = {}) => ({
  __component: "operation.list-section",
  sectionKey,
  heading,
  intro: options.intro?.map(paragraph),
  items: items.map((item, sortOrder) => ({ text: item, sortOrder })),
  outro: options.outro?.map(paragraph),
  showInPageNavigation: options.showInPageNavigation ?? true,
});

const stepsSection = (sectionKey, heading, steps) => ({
  __component: "operation.steps-section",
  sectionKey,
  heading,
  steps: steps.map((step, sortOrder) => ({ ...step, sortOrder })),
  showInPageNavigation: true,
});

const checklistSection = (sectionKey, heading, items) => ({
  __component: "operation.checklist-section",
  sectionKey,
  heading,
  items: items.map((item, sortOrder) => ({ text: item, sortOrder })),
  showInPageNavigation: true,
});

