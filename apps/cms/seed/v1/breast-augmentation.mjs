function paragraph(text) {
  return {
    type: "paragraph",
    children: [{ type: "text", text }],
  };
}

function bulletedList(items) {
  return {
    type: "list",
    format: "unordered",
    children: items.map((text) => ({
      type: "list-item",
      children: [{ type: "text", text }],
    })),
  };
}

function blocks(...paragraphs) {
  return paragraphs.map(paragraph);
}

function items(values) {
  return values.map((value, sortOrder) =>
    typeof value === "string"
      ? { text: value, sortOrder }
      : { ...value, sortOrder },
  );
}

