export function UltrakorKnowledge() {
  const [openIndex, setOpenIndex] = useState<number | null>(null);

  return (
    <section aria-labelledby="ultrakor-knowledge-title" className="ultrakor__section ultrakor-knowledge">
      <div className="ultrakor__inner">
        <h2 className="ultrakor__heading" id="ultrakor-knowledge-title">Что ещё важно знать</h2>
        <div className="ultrakor-pricing__offers ultrakor-knowledge__offers">
          {knowledgeItems.map((item, index) => {
            const open = openIndex === index;
            const contentId = `ultrakor-knowledge-content-${index}`;

            return (
              <section className={`ultrakor-pricing__offer${open ? " is-open" : ""}`} key={item.title}>
                <button aria-controls={contentId} aria-expanded={open} onClick={() => setOpenIndex(open ? null : index)} type="button">
                  <span>{item.title}</span>
                  <span aria-hidden="true">+</span>
                </button>
                <div aria-hidden={!open} className="ultrakor-pricing__offer-content" id={contentId}>
                  <div className="ultrakor-accordion__content-inner">
                    <KnowledgeContent item={item} />
                  </div>
                </div>
              </section>
            );
          })}
        </div>
      </div>
    </section>
  );
}
